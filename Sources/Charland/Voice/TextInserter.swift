import AppKit
import ApplicationServices

/// Mette il testo dettato nel campo dove stai scrivendo.
///
/// Tre modi, dal più veloce al più sicuro:
/// 1. appunti più ⌘V finto, con gli appunti ripristinati dopo che l'app li ha letti;
/// 2. scrittura carattere per carattere, dove il ⌘V finto si perde (Chrome) e nei terminali;
/// 3. niente, nei campi protetti.
@MainActor
final class TextInserter: NSObject {
    enum Outcome: String, Sendable {
        case pasted, typed
        /// Non c'è un campo dove scrivere: il testo resta nell'isola.
        case noField
        /// Campo protetto (password): non si scrive.
        case secure
        /// Manca il permesso di controllare il Mac.
        case notAllowed
    }

    /// Dove il ⌘V finto a volte si perde, e i terminali: lì si scrive carattere per carattere.
    static let typingApps: Set<String> = [
        "com.google.Chrome", "com.google.Chrome.canary", "com.brave.Browser", "com.microsoft.edgemac", "company.thebrowser.Browser",
        "com.apple.Terminal", "com.googlecode.iterm2", "dev.warp.Warp-Stable", "com.mitchellh.ghostty", "net.kovidgoyal.kitty",
        "org.alacritty", "co.zeit.hyper", "com.github.wez.wezterm",
    ]

    private static let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private var pending: PendingPaste?

    private final class PendingPaste: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
        let text: String
        var onRead: (@Sendable () -> Void)?
        init(text: String) { self.text = text }

        func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
            if type == .string { item.setString(text, forType: .string) }
            let callback = onRead
            onRead = nil
            DispatchQueue.main.async { callback?() }
        }
    }

    /// Che cosa c'è sotto il cursore: un campo di testo, un campo protetto, o niente di scrivibile.
    enum Target { case text, secure, none, unknown }

    nonisolated static func target() -> Target {
        guard let element = CaretLocator.focusedElement() else { return .unknown }
        if CaretLocator.string(element, kAXSubroleAttribute) == (kAXSecureTextFieldSubrole as String) { return .secure }
        let role = CaretLocator.string(element, kAXRoleAttribute) ?? ""
        let textRoles: Set<String> = [kAXTextFieldRole as String, kAXTextAreaRole as String, kAXComboBoxRole as String, "AXWebArea", "AXSearchField"]
        if textRoles.contains(role) { return .text }
        var settable: DarwinBoolean = false
        if AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success, settable.boolValue {
            return .text
        }
        var range: CFTypeRef?
        if AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &range) == .success { return .text }
        // Le app Chromium ed Electron spesso tengono spenta l'Accessibilità: lì non si può sapere.
        if role == "AXGroup" || role == "AXWindow" || role.isEmpty { return .unknown }
        return .none
    }

    func insert(_ text: String) async -> Outcome {
        guard !text.isEmpty else { return .noField }
        // per le prove: con CHARLAND_NON_SCRIVERE niente arriva all'app in primo piano
        if ProcessInfo.processInfo.environment["CHARLAND_NON_SCRIVERE"] != nil { return .noField }
        guard AXIsProcessTrusted() else { return .notAllowed }
        // Fuori dal thread principale, come la ricerca del cursore: se l'app davanti è bloccata l'Accessibilità
        // aspetta fino a sei secondi per ogni domanda, e qui si fermavano isola, tasti e animazioni.
        switch await Task.detached(priority: .userInitiated, operation: { Self.target() }).value {
        case .secure: return .secure
        case .none: return .noField
        case .text, .unknown: break
        }
        let bundle = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? ""
        if Self.typingApps.contains(bundle) {
            type(text)
            return .typed
        }
        await paste(text)
        return .pasted
    }

    // MARK: Appunti

    private func paste(_ text: String) async {
        let board = NSPasteboard.general
        let saved = Self.snapshot(board)
        let item = NSPasteboardItem()
        let provider = PendingPaste(text: text)
        pending = provider
        board.clearContents()
        // Il testo viene dato solo quando l'app di destinazione lo chiede: così sappiamo
        // con certezza quando l'ha letto. È marcato come passeggero, quindi i gestori
        // di appunti non lo salvano.
        item.setDataProvider(provider, forTypes: [.string])
        for type in Self.transientTypes { item.setData(Data(), forType: type) }
        board.writeObjects([item])
        let ours = board.changeCount

        await withCheckedContinuation { (continuation: CheckedContinuation<Void, Never>) in
            let once = Once()
            provider.onRead = { if once.claim() { continuation.resume() } }
            Self.postCommandV()
            // Se nessuno legge entro un secondo si va avanti comunque.
            DispatchQueue.main.asyncAfter(deadline: .now() + 1.0) { if once.claim() { continuation.resume() } }
        }
        // Un respiro perché l'app finisca di leggere, poi gli appunti tornano com'erano,
        // ma solo se nel frattempo nessuno li ha cambiati.
        try? await Task.sleep(for: .milliseconds(140))
        if board.changeCount == ours {
            Self.restore(saved, to: board)
        }
        pending = nil
    }

    private static func snapshot(_ board: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (board.pasteboardItems ?? []).map { item in
            var entry: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { entry[type] = data }
            }
            return entry
        }
    }

    private static func restore(_ saved: [[NSPasteboard.PasteboardType: Data]], to board: NSPasteboard) {
        board.clearContents()
        guard !saved.isEmpty else { return }
        let items = saved.map { entry -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            return item
        }
        board.writeObjects(items)
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = KeyCombo.keyCode(for: "v") ?? 9
        // Il segno del tasto Command sinistro: senza, le app fatte con Flutter ignorano il ⌘V finto.
        let flags = CGEventFlags(rawValue: CGEventFlags.maskCommand.rawValue | 0x8)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down) else { continue }
            event.flags = flags
            event.post(tap: .cghidEventTap)
        }
    }

    // MARK: Scrittura

    /// Scrittura a pezzi di 20 unità senza spezzare le coppie di surrogati: lo schema è quello di
    /// `TextSnippetService` di Vorssaint (GPL-3.0-or-later, Copyright (C) 2026 Vorssaint), adattato per Charland.
    private func type(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        let units = Array(text.utf16)
        var index = 0
        // Al massimo 20 unità per evento: è il limite del sistema.
        while index < units.count {
            var end = min(units.count, index + 20)
            // Non spezzare una coppia di surrogati (emoji).
            if end < units.count, UTF16.isLeadSurrogate(units[end - 1]) { end -= 1 }
            let chunk = Array(units[index..<end])
            for down in [true, false] {
                guard let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: down) else { continue }
                event.keyboardSetUnicodeString(stringLength: chunk.count, unicodeString: chunk)
                event.flags = []
                event.post(tap: .cghidEventTap)
            }
            index = end
            usleep(1500)
        }
    }
}
